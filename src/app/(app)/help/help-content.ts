/**
 * Текст справки — отдельно от вёрстки: его допишут PM и бэкенд, страница при
 * этом не меняется. Карточки короткие: что это, где найти, что с этим делать.
 *
 * `audience: 'staff'` — карточка про то, чего представитель вуза не видит
 * (аналитика, рекомендации, реестры): ему справка о закрытых разделах не нужна.
 * `image` — скриншот из `public/help/`; пока его нет, карточка без картинки.
 */

export type HelpAudience = 'all' | 'staff'

export interface HelpTopic {
  /** Якорь: на карточку можно сослаться как /help#<id>. */
  id: string
  title: string
  icon: IconName
  audience: HelpAudience
  paragraphs: string[]
  /** Где это в интерфейсе. */
  link?: { href: string; label: string }
  image?: { src: string; alt: string }
}

export interface HelpTerm {
  term: string
  definition: string
  audience: HelpAudience
}

