export function topicsFor(isUniversityRep: boolean): HelpTopic[] {
  return HELP_TOPICS.filter((topic) => !isUniversityRep || topic.audience === 'all')
}

export function termsFor(isUniversityRep: boolean): HelpTerm[] {
  return HELP_TERMS.filter((term) => !isUniversityRep || term.audience === 'all')
}
