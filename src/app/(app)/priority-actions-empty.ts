/**
 * Пустое состояние блока «Приоритетные действия» на главной (исправление 187,
 * находка ночного ревью 27.09).
 *
 * `stage.overdue` решением 180 исключён из приоритетных действий: та же
 * просрочка этапа уже названа в соседнем блоке «Требует внимания», и
 * повторять её здесь — дублировать одну проблему двумя карточками.
 * Из-за этого список приоритетных действий бывает пуст, даже когда открытые
 * рекомендации есть — просто все они оказались просрочками этапов. Раньше
 * заголовок и текст в этом случае всё равно говорили «Рекомендаций нет…
 * всё закрыто», хотя ничего не закрыто — простую просрочку просто показали
 * в другом месте экрана.
 */
export interface PriorityActionsEmptyState {
  title: string
  description: string
}

export function priorityActionsEmptyState(openRecommendationsTotal: number): PriorityActionsEmptyState {
  if (openRecommendationsTotal === 0) {
    return {
      title: 'Рекомендаций нет',
      description: 'Система ещё не собирала предложения или все они закрыты.',
    }
  }
  return {
    title: 'Приоритетных действий нет',
    // «Рядом», а не «выше» (решение 206): на широком экране блок «Требует внимания»
    // стоит слева, а не над этим; на телефоне — над ним, и «рядом» верно в обоих случаях.
    // Отложенные системой записи в пятёрку тоже не идут — они на странице рекомендаций.
    description:
      'Просрочки этапов — в соседнем блоке «Требует внимания»; отложенные системой и остальные — в «Списке задач».',
  }
}
