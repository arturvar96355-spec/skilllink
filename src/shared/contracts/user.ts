import type { UserRole } from './enums'

/** Пользователь системы. Персональные данные — минимум: ФИО, должность, рабочая почта. */
export interface UserDto {
  id: string
  /**
   * Рабочая почта — только для ADMIN и MANAGER: им она нужна, чтобы связаться
   * с ответственным. Аналитику и наблюдателю приходит null.
   */
  email: string | null
  fullName: string
  position: string | null
  role: UserRole
  /** Заполнен только у UNIVERSITY_REP. */
  universityId: string | null
  universityName: string | null
  isActive: boolean
}

/** Текущий пользователь: фронт по нему решает, какие разделы показывать. */
export interface CurrentUserDto {
  id: string
  email: string
  fullName: string
  /** Должность — шапка и личный кабинет показывают её под именем. */
  position: string | null
  role: UserRole
  universityId: string | null
  /** Название вуза представителя: чтобы шапка не делала ради него отдельный запрос. */
  universityName: string | null
  /**
   * Учётная запись эксперта хакатона (решение 147): разрушающие и изменяющие действия
   * сервер отклоняет независимо от роли. Фронт может по этому признаку прятать или
   * отключать кнопки удаления/изменения — сервер запрещает их в любом случае.
   */
  isReviewer: boolean
  /** Права текущей роли — чтобы фронт не дублировал матрицу доступа. */
  permissions: {
    canWrite: boolean
    canSeeAnalytics: boolean
    /** Пересобрать рекомендации, вести их статусы, загрузить рыночные данные (решение 98). */
    canWorkAnalytics: boolean
    canUsePortal: boolean
    /** Подтверждать материалы, вносить показатели и подавать заявки в кабинете вуза. */
    canWritePortal: boolean
    /**
     * Видит почту и телефон контактных лиц любого вуза (решение 106): ADMIN и MANAGER.
     * У представителя вуза `false`, хотя контакты своего вуза он видит: признак
     * «скрыто» приходит в самом контакте (`ContactDto.contactDetailsHidden`).
     */
    canSeeContactDetails: boolean
    isAdmin: boolean
    /**
     * Назначить, сменить или снять ответственного за вуз, сменить ответственного
     * у связки (решение 146, роль «Руководитель»): `ADMIN`, `HEAD`.
     */
    canAssignResponsible: boolean
    /**
     * Разбирать письма вузов — загрузка, повторный разбор, «Верно»/«Неверно»,
     * отклонение как спама, черновик ответа (решение 170): `ADMIN`, `HEAD`.
     * MANAGER видит обращения своих вузов через `GET /api/inbound-letters`
     * (право `INBOUND_READ`, в `/api/me` отдельным флагом не вынесено — список
     * и так пуст для остальных ролей), но это поле — только про сам разбор.
     */
    canReviewLetters: boolean
  }
  /**
   * Действующий пароль выдан администратором как временный:
   * личный кабинет просит его сменить. Определяется по журналу действий —
   * последним событием пароля было заведение или сброс, а не смена самим
   * пользователем. Отдельного поля в базе нет.
   */
  passwordTemporary: boolean
}

/**
 * Личная статистика — `GET /api/me/stats`, блок «Статистика» личного кабинета.
 *
 * Всё считается по связкам и этапам, где пользователь — ответственный, и теми же
 * правилами, что соответствующие показатели дашборда: «активная связка»,
 * «этап закрыт в срок», «этап просрочен» значат здесь то же самое.
 */
export interface CurrentUserStatsDto {
  /** Связки в работе (черновик или активна), где пользователь — ответственный. */
  activeCooperations: number
  /** Разных вузов среди этих связок. */
  universitiesInWork: number
  /** Разных программ среди этих связок. */
  programsManaged: number
  /** Доля своих этапов, закрытых не позже срока. null — «Нет данных», а не ноль. */
  stagesOnTimePercent: number | null
  /** Из скольких завершённых этапов со сроком посчитана доля. */
  stagesCompletedWithDeadline: number
  /** Свои этапы с истёкшим сроком в незакрытых связках. */
  overdueStages: number
  /** Есть ли среди связок демонстрационные — фронт обязан это показать. */
  containsMockData: boolean
  generatedAt: string
}

/**
 * Пользователь глазами администратора — `GET /api/users/:id` (вкладка «Пользователи»).
 *
 * Сколько за ним открытой работы: перед блокировкой интерфейс предупреждает,
 * что связки и этапы останутся за заблокированным, а смена роли менеджера
 * с открытыми связками отклоняется, пока их не передадут.
 */
export interface ManagedUserDto extends UserDto {
  /** Администратору почта видна всегда. */
  email: string
  /** Открытые связки (черновик, в работе, на паузе), где он ответственный. */
  openCooperations: number
  /** Незакрытые этапы открытых связок, где он ответственный. */
  openStages: number
  createdAt: string
}

/**
 * Ответ на заведение пользователя и выдачу нового пароля.
 *
 * `temporaryPassword` приходит **один раз** — в этом ответе. В базе хранится только
 * хеш bcrypt, повторно получить пароль нельзя: только выдать новый.
 */
export interface IssuedPasswordDto {
  user: UserDto
  temporaryPassword: string
}

/** Ответ на смену своего пароля — `POST /api/me/password`. */
export interface PasswordChangedDto {
  changedAt: string
  /**
   * Текущая сессия переоформлена под новый пароль (решение 109): остальные сессии
   * этого пользователя закрыты, эта продолжает работать. `false` — продлить не
   * удалось (или вход был демо-cookie без сессии): следующий запрос получит 401,
   * и фронт уведёт на вход, как при любой отозванной сессии.
   */
  sessionRenewed: boolean
}
