/**
 * «Четыре глаза» для опасных операций (решение 123).
 */
export const APPROVALS = {
  /**
   * Сколько живёт запрос: и ожидание одобрения, и использование одобренного —
   * в пределах этого срока от создания. Второй администратор рядом в течение
   * рабочего дня; неделя открытых одобрений — лишний риск.
   */
  ttlMs: 24 * 3600_000, // TEMP
} as const

/**
 * Включено ли требование одобрения. По умолчанию выключено: на демо-стенде
 * сценарий показа (demo:check) назначает и блокирует без второго администратора.
 * Включается `APPROVALS_REQUIRED=true` — в промышленном контуре и в тестах.
 * Читается при каждом вызове, как настройки интеграций.
 */
export function approvalsRequired(): boolean {
  const raw = process.env.APPROVALS_REQUIRED?.trim().toLowerCase()
  return raw === 'true' || raw === '1'
}
