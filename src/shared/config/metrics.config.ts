/**
 * Метрики сервера (решение 137): бакеты, таймауты и пути. Пороги оповещений —
 * не здесь, а в deploy/monitoring/alert-rules.yml: их считает Prometheus.
 */

/** Путь выдачи метрик: исключён из ограничения частоты и из самих метрик. */
export const METRICS_PATH = '/api/metrics'

/**
 * Бакеты времени ответа, секунды. Нижний — 25 мс: быстрее отвечает только
 * проверка живости. Верхний — 10 с: дольше идут разве что выгрузки, и отличать
 * 10 с от минуты для оповещения «p95 > 2 с» не нужно.
 */
export const HTTP_DURATION_BUCKETS: readonly number[] = [0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10]

/**
 * Проверка базы при каждом сборе (`SELECT 1`). Prometheus опрашивает раз
 * в 15–30 с; база, не ответившая за 2 с, для пользователя уже «лежит».
 */
export const DB_PING_TIMEOUT_MS = 2000

/** Разрешение измерителя задержки цикла событий, мс (perf_hooks.monitorEventLoopDelay). */
export const EVENT_LOOP_RESOLUTION_MS = 20

/**
 * Проверка цепочки журнала (`audit_chain_ok`, решение 115 + 137) читает весь журнал
 * и стоит дорого на большой базе — не на каждый сбор Prometheus (раз в 15–30 с),
 * а раз в столько миллисекунд. Подмену цепочки за 5 минут не увидеть раньше —
 * это наблюдение, а не защита: саму цепочку по-прежнему проверяет `npm run audit:verify`.
 */
export const AUDIT_CHAIN_CACHE_MS = 5 * 60 * 1000
