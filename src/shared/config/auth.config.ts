/**
 * Настройки входа. Как и остальные нормативы, вынесены сюда и помечены TEMP:
 * подобрать значения — вопрос эксплуатации, а не кода.
 */

export const LOGIN_THROTTLE = {
  /** Сколько неудачных попыток подряд допускается для одной учётной записи с одного адреса. */
  maxFailures: 5, // TEMP
  /**
   * Сколько неудачных попыток допускается с одного адреса по всем учётным записям вместе.
   *
   * Выше, чем для одной учётной записи: за одним адресом может сидеть целая
   * аудитория (одна сеть на защите), и опечатки разных людей складываются.
   * Перебор одного пароля по многим адресам электронной почты этот предел
   * всё равно останавливает.
   */
  maxFailuresPerAddress: 20, // TEMP
  /**
   * Общий потолок неудач для одной учётной записи со всех адресов вместе
   * за `accountWindowMs`. Без него перебор с разных адресов был бы бесконечным:
   * у каждого адреса свои пять попыток. Потолок высокий, чтобы посторонний
   * с одного-двух адресов не мог закрыть вход владельцу.
   */
  maxFailuresPerAccount: 50, // TEMP
  /** Окно общего потолка учётной записи, мс. */
  accountWindowMs: 60 * 60_000, // TEMP
  /** Окно, в котором попытки считаются подряд идущими, мс. */
  windowMs: 5 * 60_000, // TEMP
  /** На сколько вход закрывается после исчерпания попыток, мс. */
  blockMs: 15 * 60_000, // TEMP
  /**
   * Предел числа записей в каждом счётчике. Нужен, чтобы перебор по случайным
   * адресам не вырастил карту в памяти до размеров, которые уронят процесс.
   */
  maxTrackedKeys: 10_000,
} as const

/**
 * Проверка «не робот» на входе (captcha.ts, решение 100).
 *
 * Это задача на вычисление, а не картинка: браузер сам перебирает числа, пока
 * хеш не совпадёт, — секунда-две, нажимать ничего не нужно. Появляется не сразу,
 * а после неудач: человек, который ввёл пароль верно, её не видит.
 *
 * Счётчик адреса по всем учётным записям её не включает — за одним адресом
 * бывает целая аудитория, и опечатки соседей не должны заставлять всех решать
 * задачу. Вход при этом закрывает его предел (maxFailuresPerAddress).
 */
export const LOGIN_CAPTCHA = {
  /** После скольких неудач подряд по одной учётной записи с одного адреса. Меньше maxFailures. */
  afterFailures: 3,
  /**
   * После скольких неудач по учётной записи со всех адресов за час. Ниже общего
   * потолка (maxFailuresPerAccount): перебор с многих адресов упирается в задачу
   * задолго до того, как закроет вход владельцу.
   */
  afterFailuresPerAccount: 10,
  /**
   * Верхняя граница перебора. Браузер проверяет в среднем половину — около
   * 50 тысяч хешей: на ноутбуке доли секунды, на телефоне одна-две секунды.
   */
  maxNumber: 100_000,
  /** Сколько живёт выданная задача, мс. */
  ttlMs: 5 * 60_000,
  /** Сколько решённых задач помнится, чтобы одну нельзя было предъявить дважды. */
  maxRemembered: 10_000,
} as const

/**
 * Пароли учётных записей: временный от администратора и свой от пользователя.
 */
export const PASSWORD_POLICY = {
  /** Новый пароль, который человек задаёт себе сам, не короче этого. */
  minLength: 10, // TEMP
  /**
   * Длина временного пароля, который выдаёт администратор. Алфавит — 54 знака
   * без похожих (auth.rules.ts): 14 знаков — около 80 бит случайности.
   */
  temporaryLength: 14, // TEMP
  /**
   * bcrypt учитывает только первые 72 байта пароля: всё дальше молча отбрасывается,
   * и «длинный» пароль оказался бы короче, чем думает его владелец. Русская буква —
   * два байта, поэтому предел в байтах, а не в символах.
   */
  maxBytes: 72,
  /** Раунды bcrypt — как у демо-пользователей в prisma/seed.ts. */
  hashRounds: 10,
} as const

