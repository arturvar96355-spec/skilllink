/**
 * Ключевые вехи по порядку. Для связки прогноз строится к первой ещё не достигнутой:
 * до подписания — к подписанию; подписала — к проведению занятий; прошла обе — «достигнуто».
 *
 * Веха достигнута, когда её этап в статусе «Завершён» (по истории этапа на нужную дату).
 */
export interface ForecastMilestone {
  stageNumber: number
  /** Горизонт прогноза: дойдёт ли связка до вехи за столько дней. */
  horizonDays: number
  /** Как веха звучит в тексте: «дойдёт до …». */
  goal: string
}

