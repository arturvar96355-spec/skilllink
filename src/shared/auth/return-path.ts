/**
 * Куда вернуть человека после входа — только в пределах этого сайта.
 *
 * Адрес возврата приходит параметром `from` страницы входа, то есть его может
 * задать кто угодно ссылкой. Проверки «начинается с `/`» мало: она пропускает
 * `//evil.example` и `/\evil.example`, браузер читает их как адрес другого сайта,
 * и после ввода настоящего пароля человек окажется на чужой странице. С `reauth=1` страница
 * входа открывается даже вошедшему, с надписью «Сессия устарела» — готовая
 * приманка для фишинга.
 *
 * Разбор — тем же парсером URL, что у браузера: обратная косая, табуляция
 * и перевод строки внутри адреса обрабатываются так же, как при переходе.
 * Отдельный модуль без зависимостей: его читает клиентский код.
 */
const PROBE_ORIGIN = 'http://return-path.invalid'

export function safeReturnPath(from: string | null | undefined): string {
  if (!from || !from.startsWith('/')) return '/'
  let url: URL
  try {
    url = new URL(from, PROBE_ORIGIN)
  } catch {
    return '/'
  }
  if (url.origin !== PROBE_ORIGIN) return '/'
  return `${url.pathname}${url.search}${url.hash}`
}
