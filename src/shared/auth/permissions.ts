export type Permission = keyof typeof PERMISSIONS

export function can(user: CurrentUser, permission: Permission): boolean {
  return (PERMISSIONS[permission] as readonly UserRole[]).includes(user.role)
}

/**
 * Права, которые эксперту (флаг `is_reviewer`, решение 147) открыты и через `assertCan`:
 * только чтение и выгрузки. Список читаемых прав, а не запрещённых: новое право,
 * которое кто-то добавит и забудет здесь упомянуть, экспертам по умолчанию будет
 * недоступно — это надёжнее списка «что нельзя», который стареет тихо.
 *
 * `READ` — справочники, связи, этапы. `ANALYTICS` — рейтинги, дефициты, рекомендации
 * (без права их пересобирать — это ANALYTICS_WORK, не в списке). `UNIVERSITY_PORTAL` —
 * просмотр кабинета вуза (запись — `UNIVERSITY_PORTAL_WRITE`, не в списке). `CALENDAR` —
 * личная подписка на календарь (решение 105): не про данные системы, эксперту не мешает.
 * `CONTACT_DETAILS`, `VENDORS` — тоже только чтение (решение 106, решение 132).
 * `INBOUND_READ` — тоже только чтение (решение 170): разбор и решение по письму
 * (`INBOUND_REVIEW`) в списке нет — это как раз необратимое решение о письме.
 *
 * Экспертам эта версия отдаёт меньше, чем разрешил Артур 26.09.2026 (там же — чек-лист,
 * «взять рекомендацию в работу», встреча/документ), — выбрана более простая и надёжная
 * версия «эксперт только читает и выгружает»: перечислять «безопасные» изменения
 * по всем модулям и рисковать забыть новый деструктивный маршрут рискованнее, чем
 * временно закрыть несколько безопасных, но необязательных для экспертизы действий.
 */
const REVIEWER_ALLOWED_PERMISSIONS: ReadonlySet<Permission> = new Set<Permission>([
  'READ',
  'ANALYTICS',
  'UNIVERSITY_PORTAL',
  'CALENDAR',
  'CONTACT_DETAILS',
  'VENDORS',
  'INBOUND_READ',
])

/** Открыто ли право эксперту (решение 147): только чтение и выгрузки. */
export function isReviewerAllowed(permission: Permission): boolean {
  return REVIEWER_ALLOWED_PERMISSIONS.has(permission)
}

/** Текст отказа для эксперта — единый на все маршруты (решение 147). */
export const REVIEWER_FORBIDDEN_MESSAGE = 'Недоступно в учётной записи эксперта: действие необратимо'

/**
 * Разрушающие или изменяющие действия недоступны учётной записи эксперта (решение 147),
 * независимо от роли: `expert-admin@skilllink.demo` формально ADMIN, но `assertCan`
 * останавливает его на любом праве вне `REVIEWER_ALLOWED_PERMISSIONS`. Один вызов
 * на все ~150 мест `assertCan` во всех модулях — новый разрушающий маршрут получает
 * защиту бесплатно, если он тоже проверяет права через `assertCan`.
 */
export function assertReviewerAllowed(user: CurrentUser): void {
  if (user.isReviewer) {
    throw forbidden(REVIEWER_FORBIDDEN_MESSAGE)
  }
}

export function assertCan(user: CurrentUser, permission: Permission): void {
  if (!can(user, permission)) {
    throw forbidden('Недостаточно прав для этого действия')
  }
  if (!REVIEWER_ALLOWED_PERMISSIONS.has(permission)) {
    assertReviewerAllowed(user)
  }
}

/**
 * Почта и телефон контактных лиц вузов — только тем, кто ведёт с ними переписку:
 * ADMIN и MANAGER (право CONTACT_DETAILS, решение 106), как и почта в справочнике
 * пользователей (auth.service.ts). Аналитику и наблюдателю адреса и телефоны
 * не нужны — это персональные данные сверх цели (ст. 5 152-ФЗ, docs/PRIVACY.md).
 *
 * `universityId` — вуз, чьи контакты показываются. Представитель вуза видит
 * контакты своего вуза (как и раньше): это его же коллеги. Без `universityId`
 * (выгрузка по многим вузам) ему — нет.
 */
export function canSeeContactDetails(user: CurrentUser, universityId?: string): boolean {
  if (can(user, 'CONTACT_DETAILS')) return true
  return (
    user.role === 'UNIVERSITY_REP' &&
    universityId !== undefined &&
    user.universityId !== null &&
    user.universityId === universityId
  )
}

/**
 * Внутренние заметки сотрудников ИТ-Школы: комментарии к этапам, причины блокировок,
 * заметки по связке, комментарии в истории.
 *
 * Представитель вуза их не видит: это переписка сотрудников. Сам факт и статус
 * этапа он видит — но не то, что сотрудники пишут друг другу об этом вузе.
 */
export function canSeeInternalNotes(user: CurrentUser): boolean {
  return user.role !== 'UNIVERSITY_REP'
}

/**
 * Представитель вуза видит только свой вуз. Общий хелпер для репозиториев, а не проверка
 * в каждом маршруте.
 *
 * Учётная запись представителя без назначенного вуза — ошибка настройки. Она не должна
 * молча превращаться в доступ ко всем вузам, поэтому такой запрос отклоняется.
 */
export function universityScope(user: CurrentUser): { universityId: string } | Record<string, never> {
  if (user.role !== 'UNIVERSITY_REP') return {}

  if (!user.universityId) {
    throw forbidden('Учётной записи представителя вуза не назначен вуз. Обратитесь к администратору.')
  }
  return { universityId: user.universityId }
}

/**
 * Проверка доступа к записи конкретного вуза.
 * Чужой вуз для представителя — NOT_FOUND, а не FORBIDDEN: существование записи не раскрывается.
 */
export function isUniversityVisible(user: CurrentUser, universityId: string): boolean {
  if (user.role !== 'UNIVERSITY_REP') return true
  return user.universityId === universityId
}
