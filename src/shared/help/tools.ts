type Tools = typeof HELP_TOOLS

/** Разделы, у которых есть подразделы. */
export type HelpToolTopic = keyof Tools

/** Ключи подразделов раздела `T`; у раздела без подразделов — `never`. */
export type HelpToolKey<T extends HelpTopicId> = T extends HelpToolTopic ? keyof Tools[T] & string : never

/**
 * Ссылка на документацию: раздел и, если нужно, подраздел этого раздела.
 * Подраздел чужого раздела — ошибка типов, как и неизвестный раздел.
 */
export type HelpRef = { [T in HelpTopicId]: { topic: T; section?: HelpToolKey<T> } }[HelpTopicId]

/** Что показать в подсказке и куда вести: подраздел, если он задан, иначе раздел. */
export interface HelpEntry extends HelpToolSummary {
  anchor: string
  /** «Подробнее в документации» — справка внутри системы, сразу на подраздел. */
  href: string
}

export function helpEntry(ref: HelpRef): HelpEntry {
  const topic = HELP_TOPICS[ref.topic]
  if (ref.section) {
    const tool = (HELP_TOOLS as Readonly<Record<string, Readonly<Record<string, HelpToolSummary>>>>)[ref.topic]?.[
      ref.section
    ]
    if (tool) return { ...tool, anchor: helpAnchor(ref.topic, ref.section), href: helpHref(ref.topic, ref.section) }
  }
  return { title: topic.title, short: topic.short, how: topic.how, anchor: helpAnchor(ref.topic), href: helpHref(ref.topic) }
}
