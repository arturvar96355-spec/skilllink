/**
 * Подразделы документации — «кнопки и блоки» экранов (решение 217).
 *
 * Раздел (`topics.ts`) описывает экран или инструмент целиком. Но «?» стоит у
 * конкретной кнопки или блока — «Сменить ответственного», «Верно / Неверно»,
 * «Проверить целостность», — и подсказка про весь экран на вопрос «что будет,
 * если нажать» не отвечает. Подраздел — ровно этот ответ: заголовок, `short`
 * («что это» одной фразой) и `how` («как пользоваться»). Полный текст подраздела —
 * кто может и подробности — в `content/tools.ts`; на `/docs`, `/help` и в
 * `docs/USER_GUIDE.md` подразделы стоят внутри своего раздела, в строке
 * «Кнопки и блоки», каждый со своим якорем `<раздел>--<подраздел>`.
 *
 * Здесь только то, что читает подсказка: полный текст в браузер не едет.
 * Ключ подраздела — часть адреса: переименовать — сломать чужие ссылки.
 */

export interface HelpToolSummary {
  title: string
  /** Одна фраза «что это» — первая строка подсказки. */
  short: string
  /** Одна-две строки «как пользоваться» — с точными названиями кнопок. */
  how: string
}

