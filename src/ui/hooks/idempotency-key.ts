'use client'

import { useState } from 'react'

/**
 * Ключ идемпотентности форм создания (решение 133/183): один на одно открытие
 * формы — двойной щелчок, обрыв сети или повтор после отказа с этим же ключом
 * сервер не превращает во вторую запись (`withIdempotency`, shared/idempotency).
 *
 * Модальные формы создания в этом приложении монтируются заново на каждое
 * открытие (родитель рисует их условно — `{isOpen && <CreateXModal />}`),
 * поэтому обычного `useState` с ленивым инициализатором достаточно: новый
 * ключ появляется сам вместе с новым экземпляром компонента.
 *
 * Форма, которая остаётся на странице без своего открытия и закрытия (заявка
 * в кабинете вуза), должна звать `renew()` после успешной отправки — иначе
 * вторая, настоящая заявка с тем же телом молча получила бы ответ первой.
 */
export function useIdempotencyKey(): { key: string; renew: () => void } {
  const [key, setKey] = useState(() => crypto.randomUUID())
  return { key, renew: () => setKey(crypto.randomUUID()) }
}
