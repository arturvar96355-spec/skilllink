/**
 * Чистая математика бегущей строки (решение 186).
 *
 * `Ticker.tsx` двигает ленту `requestAnimationFrame`'ом, а не CSS-анимацией:
 * так положение можно остановить, перетащить и отпустить без прыжка. Здесь —
 * две вещи, которые не должны знать про DOM и React: заворот смещения
 * в бесшовную петлю и порог «это клик или уже перетаскивание».
 */

/**
 * Смещение ленты, завёрнутое в диапазон `(-width, 0]`.
 *
 * Содержимое повторено в разметке дважды подряд, и одна копия занимает
 * `width` пикселей — сдвиг на `-width` выглядит точно как сдвиг `0`, шва не
 * видно. Функция общая для двух источников смещения: автопрокрутка уводит
 * его в минус бесконечность со временем, перетаскивание может одним движением
 * пальца унести за любой край ленты — оба случая одинаково заворачиваются
 * в этот диапазон.
 */
export function wrapTrackOffset(offset: number, width: number): number {
  if (!Number.isFinite(width) || width <= 0) return 0
  const wrapped = offset % width
  if (wrapped === 0) return 0 // не отдаём -0: смещения нет — значит нет
  return wrapped > 0 ? wrapped - width : wrapped
}

/**
 * Курсор или палец сдвинулись больше порога — это перетаскивание ленты,
 * а не клик по ссылке внутри неё. Порог общий по обеим осям: маленькое
 * дрожание руки при обычном клике не должно засчитаться как перетаскивание.
 */
export function isDragGesture(dx: number, dy: number, thresholdPx: number): boolean {
  return Math.abs(dx) > thresholdPx || Math.abs(dy) > thresholdPx
}
