-- Версия сессий пользователя (решение 109): отзыв уже выданных JWT-сессий.
-- Номер кладётся в токен при входе; не совпал с базой — сессия недействительна.
-- Растёт при смене и сбросе пароля, блокировке и смене роли.
--
-- Всем существующим строкам проставляется 0, а токен без версии (выдан до этой
-- миграции) сервер тоже считает версией 0 — выкладка никого не разлогинивает.
-- Операция быстрая: в PostgreSQL 11+ ADD COLUMN с константным DEFAULT не
-- переписывает таблицу.
--
-- Откат (Prisma down-миграций не пишет — выполнить вручную; после отката
-- отозванные сессии снова заработают до истечения своих восьми часов):
--   ALTER TABLE "users" DROP COLUMN "session_version";

-- AlterTable
ALTER TABLE "users" ADD COLUMN "session_version" INTEGER NOT NULL DEFAULT 0,
    -- Версия только растёт от нуля: отрицательная значила бы ручную правку.
    ADD CONSTRAINT "users_session_version_check" CHECK ("session_version" >= 0);
